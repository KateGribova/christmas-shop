document.addEventListener('click', function (event) {
    if (event.target.matches('.menu__list-item-burger') || event.target.matches('.menu__list-item-burger__liner')) {
      scroll(0, 0);
      document.querySelector('.menu').classList.toggle('open');
      document.querySelector('body').classList.toggle('not-scroll');
    }

    if ((event.target.matches('.menu__list-item.active') || event.target.matches('.menu__list-item-link.burger')) && document.querySelector('.menu').classList.contains('open')){
      document.querySelector('.menu').classList.remove('open');
      document.querySelector('body').classList.remove('not-scroll');
    }
});

document.querySelector('.gifts-block').addEventListener('click', (event) => {
  const modal = document.querySelector('.modal');
  const modalClose = document.querySelector('.modal__close');
  const subtitle = modal.querySelector('.modal__description__base__subtitle');

  const card = event.target.closest('.gifts-block-card');
  const giftName = card.querySelector('.gifts-block-card__title').textContent.trim();
  const giftData = gifts.find(gift => gift.name === giftName);

  modal.querySelector('.modal__description__base__title').textContent = giftData.name;
  modal.querySelector('.modal__description__base__subtitle').textContent = giftData.category;
  modal.querySelector('.modal__description__base__text').textContent = giftData.description;

  modal.querySelector('.modal__description__superpowers__wrapper__text.live.score').textContent = giftData.superpowers.live;
  modal.querySelector('.modal__description__superpowers__wrapper__text.create.score').textContent = giftData.superpowers.create;
  modal.querySelector('.modal__description__superpowers__wrapper__text.love.score').textContent = giftData.superpowers.love;
  modal.querySelector('.modal__description__superpowers__wrapper__text.dream.score').textContent = giftData.superpowers.dream;

  function resetSnowBalls() {
    const allPaths = modal.querySelectorAll('.modal__description__superpowers__wrapper__imgs svg path');
    allPaths.forEach((path) => {
      path.classList.remove('opacity');
    });
  }

  resetSnowBalls();

  let str;
  str = giftData.superpowers.live;
  str = str.slice(1, 2);
  let n = Number(str);
  console.log(n);

  for (let i = n; i <= 4; i++){
    modal.querySelectorAll('.modal__description__superpowers__wrapper__imgs.live svg path')[i].classList.add('opacity');
  }

  str = giftData.superpowers.create;
  str = str.slice(1, 2);
  n = Number(str);
  console.log(n);

  for (let i = n; i <= 4; i++){
    modal.querySelectorAll('.modal__description__superpowers__wrapper__imgs.create svg path')[i].classList.add('opacity');
  }

  str = giftData.superpowers.love;
  str = str.slice(1, 2);
  n = Number(str);
  console.log(n);

  for (let i = n; i <= 4; i++){
    modal.querySelectorAll('.modal__description__superpowers__wrapper__imgs.love svg path')[i].classList.add('opacity');
  }

  str = giftData.superpowers.dream;
  str = str.slice(1, 2);
  n = Number(str);
  console.log(n);
  
  for (let i = n; i <= 4; i++){
    modal.querySelectorAll('.modal__description__superpowers__wrapper__imgs.dream svg path')[i].classList.add('opacity');
  }
  
  subtitle.classList.remove('work', 'harmony', 'health');
  if (subtitle.textContent.trim() == "For Work"){
    subtitle.classList.add('work');
    modal.querySelector('.modal__img-pic').src = './home/img/for-work.png';
  } else if (subtitle.textContent.trim() == "For Harmony"){
    subtitle.classList.add('harmony');
    modal.querySelector('.modal__img-pic').src = './home/img/for-harmony.png';
  } else if (subtitle.textContent.trim() == "For Health") {
    subtitle.classList.add('health');
    modal.querySelector('.modal__img-pic').src = './home/img/for-health.png';
  }
  
  modal.style.display = 'flex';
  document.querySelector('body').classList.add('not-scroll');
  
  const closeModal = () => {
    modal.style.display = 'none';
    document.querySelector('body').classList.remove('not-scroll');
  };

  modalClose.addEventListener('click', closeModal);
  
  modal.addEventListener('click', (event) => {
    if (!event.target.closest('.modal-wrapper')) {
        closeModal();
    }
  });
});

window.addEventListener('scroll', function(){
  if (scrollY > 300)
    document.querySelector('.scroll-to-top').classList.add('not-none');
  else
  document.querySelector('.scroll-to-top').classList.remove('not-none');
});

document.querySelector('.scroll-to-top').addEventListener('click', function() {
  scroll(0, 0);
});

window.addEventListener('resize', () => {
  if (document.body.clientWidth > 768 && document.querySelector('.menu.open'))
    document.querySelector('body').classList.remove('not-scroll');
  else if (document.body.clientWidth < 768 && document.querySelector('.menu.open'))
    document.querySelector('body').classList.add('not-scroll');
});