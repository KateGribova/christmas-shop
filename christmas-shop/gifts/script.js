let gifts = JSON.parse(JsonGifts);

function loadPage(){
    let giftsBlock = document.querySelector('.gifts-block');
    let cards = document.querySelectorAll('.gifts-block-card');
    cards.forEach(card => card.remove());

    document.querySelector('.gifts-menu__title.active').classList.remove('active');
    document.querySelector('.gifts-menu__title.all').classList.add('active');

    let giftsBlockCard;
    for (let i = 0; i < 36; i++){
        giftsBlockCard = document.createElement('div');
        giftsBlockCard.classList.add('gifts-block-card');
        giftsBlock.append(giftsBlockCard);

            
        let giftsBlockCardImg = document.createElement('div');
        giftsBlockCardImg.classList.add('gifts-block-card__img');
        let image = document.createElement('img');
        image.classList.add('gifts-block-card__img-pic');
        
        let title = gifts[i].name;
        let subtitle = gifts[i].category;
        let giftsBlockCardText = document.createElement('div');
        giftsBlockCardText.classList.add('gifts-block-card__text');
        let h4 = document.createElement('h4');
        h4.classList.add('gifts-block-card__subtitle');
        h4.innerHTML = subtitle;
        let h3 = document.createElement('h3');
        h3.classList.add('gifts-block-card__title')
        h3.innerHTML = title;
        
        if (gifts[i].category == "For Work"){
            h4.classList.add('work');
            image.src = './gifts/img/for-work.png';
        } else if (gifts[i].category == "For Health"){
            h4.classList.add('health');
            image.src = './gifts/img/for-health.png';
        } else if (gifts[i].category == "For Harmony"){
            h4.classList.add('harmony');
            image.src = './gifts/img/for-harmony.png';
        }
        
        giftsBlockCardImg.append(image);
        giftsBlockCard.append(giftsBlockCardImg, giftsBlockCardText);
        giftsBlockCardText.append(h4, h3);
    }
}

document.querySelector('.gifts-menu__title.all').addEventListener('click', loadPage);
document.addEventListener('DOMContentLoaded', loadPage);

