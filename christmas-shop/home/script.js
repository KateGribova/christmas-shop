const DATE_NY = new Date(Date.UTC(2026,0,1,0,0,0));
const TOTAL_WIDTH_SLIDER = 1993;

function updateTime(){
    let nowDate = new Date();
    gapDate = DATE_NY - nowDate;

    let days = Math.floor(gapDate / 1000 / 60 / 60 / 24);
    let hours = Math.floor(gapDate / 1000 / 60 / 60) % 24;
    let minutes = Math.floor(gapDate / 1000 / 60) % 60;
    let seconds = Math.floor(gapDate / 1000) % 60;

    document.querySelector('.CTA-content-timer-block__number.days').innerHTML = days;
    document.querySelector('.CTA-content-timer-block__number.hours').innerHTML = hours;
    document.querySelector('.CTA-content-timer-block__number.minutes').innerHTML = minutes;
    document.querySelector('.CTA-content-timer-block__number.seconds').innerHTML = seconds;
}

function sliderHome(){
    let click = 0;
    let currentClick = 0;
    let currentPosition = 0;

    let WIDTH = window.screen.width;
    let VISIBLE_SLIDER = document.querySelector('.slider-wrapper__images').offsetWidth;

    const sliderImages = document.querySelector('.slider-wrapper__images');
    const buttonRight = document.querySelector('.slider-wrapper__control-button.right');
    const buttonLeft = document.querySelector('.slider-wrapper__control-button.left');

    function updateButton() {
        buttonRight.disabled = currentClick === click;
        buttonLeft.disabled = currentClick === 0;
    }
    
    function updateSlider(){
        WIDTH = window.screen.width;
        VISIBLE_SLIDER = document.querySelector('.slider-wrapper__images').offsetWidth;
        click = 0;
        currentClick = 0;
        currentPosition = 0;

        if (WIDTH > 768)
            click = 3;
        else
            click = 6;
        let transfer = (TOTAL_WIDTH_SLIDER - VISIBLE_SLIDER) / click;

        sliderImages.style.transform = `translateX(${currentPosition}px)`;
        updateButton();

        return transfer;
    }

    let transfer = updateSlider();
    updateButton();

    buttonRight.addEventListener('click', () => {
        if (currentClick < click){
            currentClick += 1;
            currentPosition -= transfer;
            sliderImages.style.transform = `translateX(${currentPosition}px)`;
            updateButton();
        }
    })

    buttonLeft.addEventListener('click', () => {
        if (currentClick > 0){
            currentClick -= 1;
            currentPosition += transfer;
            sliderImages.style.transform = `translateX(${currentPosition}px)`;
            updateButton();
        }
    })

    window.addEventListener('resize', () => {
        (transfer = updateSlider());
    });
}


